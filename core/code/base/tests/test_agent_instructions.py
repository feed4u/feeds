"""Guards the repository's agent instructions (AGENTS.md / CLAUDE.md).

AGENTS.md is generated by the owner model's scaffold.py from its template plus
AGENTS.local.md; CLAUDE.md only imports it, so Claude Code and Codex read the
same guidance. These tests keep that true and keep the documented paths real.

Run: python3 -m unittest discover -s core/code/base/tests -v
"""

from __future__ import annotations

import importlib.util
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SCAFFOLD = Path("/mnt/data1/projects/owner-model/scaffold.py")
MARKER = "<!-- owner-model:generated"

# Retired top-level trees (gitignored; may linger on disk in an old checkout);
# guidance must not send agents there.
RETIRED = ("4u/", "k5-security-news/", "readd/", "economic/", "economic-4u/")
# Documented paths that are created locally and gitignored, so absent in a checkout.
LOCAL_ONLY = {"core/web/.env.local", "core/web/public/data/"}


def _read(name: str) -> str:
    return (ROOT / name).read_text(encoding="utf-8")


class InstructionFileTests(unittest.TestCase):
    def test_claude_md_only_imports_agents_md(self):
        self.assertEqual((ROOT / "CLAUDE.md").read_bytes(), b"@AGENTS.md\n")

    def test_agents_md_is_generated_and_ends_with_local_guidance(self):
        agents = _read("AGENTS.md")
        local = _read("AGENTS.local.md")
        self.assertTrue(agents.startswith(MARKER))
        self.assertTrue(agents.endswith("\n" + local.strip() + "\n"))

    @unittest.skipUnless(SCAFFOLD.is_file(), "owner-model scaffold not on this host")
    def test_agents_md_matches_scaffold_render(self):
        spec = importlib.util.spec_from_file_location("owner_model_scaffold", SCAFFOLD)
        scaffold = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(scaffold)
        template = (Path(scaffold.TEMPLATES) / "AGENTS.md").read_text(encoding="utf-8")
        wanted = scaffold.render(template, _read("AGENTS.local.md"), "AGENTS.local.md")
        self.assertEqual(_read("AGENTS.md"), wanted)


class LocalGuidanceTests(unittest.TestCase):
    def setUp(self):
        self.text = _read("AGENTS.local.md")

    def test_documented_repo_paths_exist(self):
        paths = set(re.findall(r"(?<![\w/.-])((?:core|\.github)/[\w./-]*)", self.text))
        self.assertTrue(paths)
        missing = []
        for path in sorted(paths):
            path = path.rstrip(".")
            if "<" in path or path in LOCAL_ONLY:
                continue
            if not (ROOT / path).exists():
                missing.append(path)
        self.assertEqual(missing, [])

    def test_documented_python_entry_points_accept_vertical_flag(self):
        scripts = set(re.findall(r"python3 (core/code/\S+\.py) --vertical", self.text))
        self.assertTrue(scripts)
        for script in sorted(scripts):
            source = (ROOT / script).read_text(encoding="utf-8")
            self.assertTrue(
                "add_path_cli_arguments(parser)" in source or '"--vertical"' in source,
                f"{script} has no --vertical flag",
            )

    def test_retired_directories_are_not_documented(self):
        tokens = re.findall(r"`([^`]+)`", self.text)
        for retired in RETIRED:
            self.assertFalse(
                [t for t in tokens if t.startswith(retired)],
                f"AGENTS.local.md points at retired {retired}",
            )


if __name__ == "__main__":
    unittest.main()
